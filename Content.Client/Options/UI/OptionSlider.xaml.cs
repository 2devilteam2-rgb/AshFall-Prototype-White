using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;

namespace Content.Client.Options.UI;

/// <summary>
/// Standard UI control used for sliders in the options menu. Intended for use with <see cref="OptionsTabControlRow"/>.
/// Features hover highlight and accordion description.
/// </summary>
/// <seealso cref="OptionsTabControlRow.AddOptionSlider"/>
/// <seealso cref="OptionsTabControlRow.AddOptionPercentSlider"/>
[GenerateTypedNameReferences]
public sealed partial class OptionSlider : Control
{
    private static readonly StyleBoxFlat HoverStyle = new()
    {
        BackgroundColor = Color.FromHex("#1E2229"),
        BorderColor = Color.FromHex("#E58229"),
        BorderThickness = new Thickness(2, 0, 0, 0),
        ContentMarginLeftOverride = 4
    };

    private string? _description;

    public OptionSlider()
    {
        RobustXamlLoader.Load(this);

        RowPanel.MouseFilter = MouseFilterMode.Pass;
        NameLabel.MouseFilter = MouseFilterMode.Pass;

        RowPanel.OnMouseEntered += _ =>
        {
            RowPanel.PanelOverride = HoverStyle;
            if (!string.IsNullOrWhiteSpace(_description))
                DescriptionLabel.Visible = true;
        };

        RowPanel.OnMouseExited += _ =>
        {
            RowPanel.PanelOverride = null;
            DescriptionLabel.Visible = false;
        };
    }

    /// <summary>
    /// The text describing what this slider controls.
    /// </summary>
    public string? Title
    {
        get => NameLabel.Text;
        set => NameLabel.Text = value;
    }

    /// <summary>
    /// Tooltip text for the option, displayed when hovering anywhere over the row.
    /// </summary>
    public new string? ToolTip
    {
        get => base.ToolTip;
        set
        {
            base.ToolTip = value;
            NameLabel.ToolTip = value;
            Slider.ToolTip = value;
        }
    }

    /// <summary>
    /// Tooltip/description text for the option.
    /// </summary>
    public string? Description
    {
        get => _description;
        set
        {
            _description = value;
            DescriptionLabel.Text = value;
            ToolTip = value;
        }
    }
}
